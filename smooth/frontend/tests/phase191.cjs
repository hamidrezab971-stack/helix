// Real Chromium + isolated HTTP/WebSocket backend. No production credentials,
// database, uploads or messages are used. Delays wrap actual directory responses.
const { chromium, expect } = require('playwright/test')
const assert = require('node:assert/strict')
const fs = require('node:fs')
const path = require('node:path')
const h = require('./phase8.cjs')
let browser
const output = process.env.HELIX_QA_DIR || path.join(require('node:os').tmpdir(), `helix-phase191-qa-${Date.now()}`)
const nav = page => page.getByRole('navigation', { name: 'Main navigation' })
const tab = (page, label) => nav(page).getByRole('button', { name: label, exact: true })
async function back(page) { await page.evaluate(() => history.back()) }
async function viewport(page, width, height = 800) {
  await page.setViewportSize({ width, height })
  await expect.poll(() => page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
}
async function main() {
  await h.startBackend()
  browser = await chromium.launch({ headless: true })
  const context = await browser.newContext({ isMobile: true, hasTouch: true, viewport: { width: 390, height: 800 } })
  const otherContext = await browser.newContext({ viewport: { width: 1280, height: 800 } })
  const alice = await h.newPage(context), bob = await h.newPage(otherContext)
  const directoryRequests = [], creates = []
  alice.on('request', request => {
    if (new URL(request.url()).pathname === '/api/users') directoryRequests.push(request.url())
    if (request.method() === 'POST' && request.url().includes('/conversations/with/')) creates.push(request.url())
  })
  await h.registerAndLogin(alice, h.names.alice)
  await h.registerAndLogin(bob, h.names.bob)
  await expect(tab(alice, 'Chats')).toHaveAttribute('aria-current', 'page')
  await expect(alice.locator('.user-row')).toHaveCount(0)
  await expect(alice.locator('#user-search')).toHaveCount(0)
  assert.equal(directoryRequests.length, 0)
  const connections = await alice.evaluate(() => window.realtimeTest.authenticated)
  const closed = await alice.evaluate(() => window.realtimeTest.closed)

  await alice.getByRole('button', { name: 'New chat', exact: true }).click()
  await expect(alice.getByRole('heading', { name: 'Contacts', exact: true })).toBeVisible()
  await expect(alice.locator('.user-row').filter({ hasText: `@${h.names.bob}` })).toBeVisible()
  await expect(alice.locator('.user-row').filter({ hasText: `@${h.names.alice}` })).toHaveCount(0)
  await alice.locator('#user-search').fill(h.names.bob.toUpperCase())
  await alice.locator('.user-row').filter({ hasText: `@${h.names.bob}` }).click()
  await expect(alice.locator('#chat-title')).toHaveText(`@${h.names.bob}`)
  await expect(nav(alice)).toBeHidden()
  await expect(alice.getByRole('button', { name: 'New chat' })).toBeHidden()
  await alice.locator('#message-content').fill('Unsent draft سلام')
  await back(alice)
  await expect(tab(alice, 'Contacts')).toHaveAttribute('aria-current', 'page')
  await expect(alice.locator('#user-search')).toHaveValue(h.names.bob.toUpperCase())
  await alice.locator('.user-row').filter({ hasText: `@${h.names.bob}` }).click()
  await expect(alice.locator('#message-content')).toHaveValue('Unsent draft سلام')
  assert.equal(creates.length, 1)
  await alice.locator('#message-content').fill('')
  const sent = await h.send(alice, 'سلام Helix — retained conversation')
  await h.select(bob, h.names.alice)
  await h.status(alice, sent.content, 'Read')
  await back(alice)
  await h.navigate(alice, 'Chats')
  await expect(alice.getByLabel('Recent conversations')).toContainText('سلام Helix')
  console.log('PASS Chats-only, FAB to Contacts, self exclusion, case-insensitive Contacts, existing conversation reuse, draft retention, send/read and mobile Back')

  for (let index = 0; index < 3; index++) {
    await alice.getByRole('button', { name: 'Search', exact: true }).click()
    await expect(alice.locator('#chat-search')).toBeFocused()
    await alice.locator('#chat-search').fill(h.names.bob.toUpperCase())
    await expect(alice.getByLabel('Matching conversations')).toContainText(h.names.bob)
    await alice.getByRole('button', { name: 'Clear search', exact: true }).click()
    await expect(alice.locator('#chat-search')).toHaveValue('')
    await expect(alice.locator('#chat-search')).toBeFocused()
    await alice.keyboard.press('Escape')
    await expect(alice.locator('#chat-search')).toBeHidden()
    await expect(alice.getByRole('button', { name: 'Search', exact: true })).toBeFocused()
  }
  await alice.getByRole('button', { name: 'Search', exact: true }).click()
  await alice.locator('#chat-search').fill(h.names.bob)
  await alice.getByLabel('Matching conversations').locator('.recent-row').click()
  await expect(alice.locator('#message-content')).toBeVisible()
  await back(alice)
  await expect(alice.locator('#chat-search')).toBeVisible()
  await expect(alice.locator('#chat-search')).toHaveValue(h.names.bob)
  await alice.getByRole('tab', { name: 'People', exact: true }).click()
  await expect(alice.getByRole('tabpanel', { name: 'People', exact: true }).locator('.user-row')).toContainText(h.names.bob)

  const heldQuery = h.names.bob.slice(0, -1)
  let releaseOld
  const held = new Promise(resolve => { releaseOld = resolve })
  let captureOld
  const captured = new Promise(resolve => { captureOld = resolve })
  await alice.route('**/api/users?*', async route => {
    const query = new URL(route.request().url()).searchParams.get('search')
    const response = await route.fetch()
    if (query === heldQuery) { captureOld(); await held }
    try { await route.fulfill({ response }) } catch { /* Aborted browser request. */ }
  })
  await alice.locator('#chat-search').fill(heldQuery)
  await captured
  await expect(alice.getByText('Looking for people…', { exact: true })).toBeVisible()
  await alice.locator('#chat-search').fill('zz_no_such_person')
  await expect(alice.getByText('No people found.', { exact: true })).toBeVisible()
  releaseOld()
  await alice.unroute('**/api/users?*')
  await expect(alice.getByRole('tabpanel', { name: 'People', exact: true }).locator('.user-row')).toHaveCount(0)
  let fail = true
  await alice.route('**/api/users?*', async route => {
    if (fail) { fail = false; await route.fulfill({ status: 503, contentType: 'application/json', body: '{"detail":"isolated QA failure"}' }) }
    else await route.continue()
  })
  await alice.locator('#chat-search').fill('bob_')
  await expect(alice.getByRole('alert')).toHaveText('Unable to load people.')
  await alice.getByRole('button', { name: 'Try again', exact: true }).click()
  await expect(alice.getByRole('tabpanel', { name: 'People', exact: true }).locator('.user-row')).toContainText(h.names.bob)
  await alice.unroute('**/api/users?*')
  await back(alice)
  await expect(tab(alice, 'Chats')).toHaveAttribute('aria-current', 'page')
  assert.equal(await alice.evaluate(() => window.realtimeTest.authenticated), connections)
  assert.equal(await alice.evaluate(() => window.realtimeTest.closed), closed)
  console.log('PASS repeated Search focus/clear/Escape, search-chat-Back query retention, Chats/People results, stale-response cancellation, loading/empty/error/retry, no duplicate WebSocket authentication')

  await h.navigate(alice, 'Settings')
  await alice.getByRole('button', { name: 'Switch to light theme' }).click()
  await expect(alice.locator('html')).toHaveAttribute('data-theme', 'light')
  await alice.getByRole('button', { name: 'Switch to dark theme' }).click()
  await h.navigate(alice, 'Profile')
  await expect(alice.getByRole('region', { name: 'Your profile' })).toContainText(h.names.alice)
  await expect(alice.getByText('Member since', { exact: true })).toBeVisible()
  await back(alice)
  await expect(tab(alice, 'Chats')).toHaveAttribute('aria-current', 'page')
  // Seed enough real, disposable conversations to verify scroll restoration
  // and maximum-length usernames against the existing API, then reload once.
  for (let index = 0; index < 14; index++) {
    const username = `nav_${index}_${Date.now()}`.padEnd(30, 'x')
    const registered = await context.request.post('http://127.0.0.1:8000/api/auth/register', { data: { username, password: 'password123', altcha: await require('./captcha.cjs').solve(context.request,'register') } })
    assert.equal(registered.status(), 201)
    const peer = await registered.json()
    const status = await alice.evaluate(async id => {
      const response = await fetch(`/api/conversations/with/${id}`, { method: 'POST', headers: { Authorization: `Bearer ${localStorage.getItem('smooth_access_token')}` } })
      return response.status
    }, peer.id)
    assert.equal(status, 201)
  }
  await alice.reload()
  await alice.waitForFunction(() => window.realtimeTest.authenticated === 1)
  const chats = alice.locator('.sidebar-content[aria-label="Chats"]')
  await expect(chats.locator('.recent-row')).toHaveCount(15)
  await chats.evaluate(el => { el.scrollTop = el.scrollHeight })
  const chatScroll = await chats.evaluate(el => el.scrollTop)
  assert.ok(chatScroll > 0)
  await alice.getByRole('button', { name: 'Search', exact: true }).click()
  await alice.locator('#chat-search').fill('missing')
  await expect(alice.getByText('No matching chats.', { exact: true })).toBeVisible()
  await back(alice)
  await expect.poll(() => chats.evaluate(el => el.scrollTop)).toBe(chatScroll)
  await h.navigate(alice, 'Contacts')
  await alice.locator('#user-search').fill('')
  const contacts = alice.getByLabel('User directory', { exact: true })
  await expect(contacts.locator('.user-row')).toHaveCount(15)
  await contacts.evaluate(el => { el.scrollTop = el.scrollHeight })
  const contactScroll = await contacts.evaluate(el => el.scrollTop)
  assert.ok(contactScroll > 0)
  const requestCount = directoryRequests.length
  await h.navigate(alice, 'Chats')
  await h.navigate(alice, 'Contacts')
  await expect.poll(() => contacts.evaluate(el => el.scrollTop)).toBe(contactScroll)
  assert.equal(directoryRequests.length, requestCount)
  await h.navigate(alice, 'Chats')
  console.log('PASS Chats/Search and Contacts scroll restoration, bounded directory cache reuse and actual 30-character usernames')
  fs.mkdirSync(output, { recursive: true })
  for (const width of [360, 390, 430, 768, 1280]) {
    await viewport(alice, width)
    const fab = await alice.getByRole('button', { name: 'New chat' }).boundingBox()
    const navigation = await nav(alice).boundingBox()
    assert.ok(fab.width >= 48 && fab.height >= 48)
    assert.ok(fab.y + fab.height < navigation.y)
    assert.ok(fab.x >= 0 && fab.x + fab.width <= width)
    await alice.screenshot({ path: path.join(output, `${width}-chats.png`) })
    await alice.getByRole('button', { name: 'New chat' }).click()
    await expect(alice.locator('#user-search')).toBeVisible()
    await alice.screenshot({ path: path.join(output, `${width}-contacts.png`) })
    await h.navigate(alice, 'Chats')
  }
  await viewport(alice, 390, 380)
  await alice.getByRole('button', { name: 'Search', exact: true }).click()
  await expect(alice.locator('#chat-search')).toBeFocused()
  const inputBox = await alice.locator('#chat-search').boundingBox()
  assert.ok(inputBox.y >= 0 && inputBox.y + inputBox.height < 380)
  await alice.emulateMedia({ reducedMotion: 'reduce' })
  assert.equal(await alice.locator('.navigation-searchbar').evaluate(el => getComputedStyle(el).animationDuration), '0s')
  await back(alice)
  assert.deepEqual(h.errors, [])
  console.log(`PASS Settings/Profile, 360/390/430/768/1280px FAB/nav/overflow, simulated keyboard height, reduced motion; screenshots: ${output}`)
}
main().catch(async error => { console.error(error); process.exitCode = 1; await h.captureFailure(browser, error) }).finally(async () => {
  if (browser) await browser.close()
  await h.stopBackend()
  fs.rmSync(h.temporary, { recursive: true, force: true })
})
